"""Generate ingredient colour labels from the real ingredient WebP artwork."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public/business/ingredients"
OUTPUT = ROOT / "src/game/business/ingredientBeltColor.ts"
PALETTE = [
    ("red", "#D9392B"), ("orange", "#F28C28"), ("yellow", "#F4C430"),
    ("green", "#4C9A2A"), ("brown", "#8B5A2B"), ("purple", "#7B4BA3"),
    ("cream", "#F6F0E4"), ("grey", "#8E8A86"),
]


def rgb_to_lab(rgb):
    def linear(c):
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = map(linear, rgb)
    x = (r * 0.4124564 + g * 0.3575761 + b * 0.1804375) / 0.95047
    y = r * 0.2126729 + g * 0.7151522 + b * 0.072175
    z = (r * 0.0193339 + g * 0.119192 + b * 0.9503041) / 1.08883

    def f(t):
        return t ** (1 / 3) if t > 216 / 24389 else (24389 / 27 * t + 16) / 116

    fx, fy, fz = f(x), f(y), f(z)
    return (116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz))


# The picture's average colour lands on brown for dark or speckled food that every player knows by another
# colour (a beetroot is not brown), and nothing at all reaches purple. These few are set by hand; the rest
# are still matched by their picture. Checked by eye against public/business/ingredients/<id>.webp.
OVERRIDES = {
    "beetroot": "purple",
    "eggplant": "purple",
    "grapes": "purple",
    "radish": "red",
    "pineapple": "yellow",
    "garlic": "yellow",
}

palette_lab = [(name, rgb_to_lab(tuple(int(hexcode[i:i+2], 16) for i in (1, 3, 5)))) for name, hexcode in PALETTE]
rows = []
for image_path in sorted(SOURCE.glob("*.webp")):
    with Image.open(image_path) as image:
        image = image.convert("RGBA")
        image.thumbnail((48, 48))
        pixels = [pixel[:3] for pixel in image.getdata() if pixel[3] > 16]
    average = tuple(sum(pixel[channel] for pixel in pixels) / len(pixels) for channel in range(3))
    lab = rgb_to_lab(average)
    name = min(palette_lab, key=lambda candidate: sum((lab[i] - candidate[1][i]) ** 2 for i in range(3)))[0]
    rows.append((image_path.stem, OVERRIDES.get(image_path.stem, name)))

color_ids = {name: index for index, (name, _) in enumerate(PALETTE[:6])}
lines = [
    "/** Generated by scripts/make-belt-palette.py from public/business/ingredients/*.webp. */",
    'import type { BeltColor } from "./platingBelt";',
    "",
    "export const INGREDIENT_BELT_COLOR: Record<string, BeltColor> = {",
]
for ingredient, name in rows:
    if name not in color_ids:
        # Cream/grey classify only visual garnish and map to the nearest food hue for game pieces.
        name = "yellow" if name == "cream" else "brown"
    lines.append(f'  "{ingredient}": {color_ids[name]},')
lines.extend(["};", ""])
OUTPUT.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {len(rows)} ingredient colours to {OUTPUT.relative_to(ROOT)}")
