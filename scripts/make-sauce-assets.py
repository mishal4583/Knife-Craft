def write_sheet_table() -> None:
    """Writes src/components/kc/sauce/sauceSheets.ts from the built sheets (the tight alpha box of each cell)."""
    lines = [
        "/* GENERATED by scripts/make-sauce-assets.py: the tight pixel box [x, y, w, h] of every cell of the Sauce Station sheets (public/business/sauce/). Do not edit. */",
        "export type SheetInfo = { w: number; h: number; cols: number; rows: number; boxes: readonly (readonly [number, number, number, number])[] };",
        "export const SHEETS: Readonly<Record<string, SheetInfo>> = {",
    ]
    for name, (cols, rows) in SHEETS.items():
        path = os.path.join(OUT, name + ".webp")
        if not os.path.exists(path):
            continue
        im = Image.open(path).convert("RGBA")
        w, h = im.size
        cw, ch = w // cols, h // rows
        a = np.array(im.getchannel("A"))
        boxes = []
        for r in range(rows):
            for c in range(cols):
                cell = a[r * ch:(r + 1) * ch, c * cw:(c + 1) * cw] > 16
                ys, xs = np.where(cell)
                if len(xs) == 0:
                    boxes.append((c * cw, r * ch, cw, ch))
                else:
                    x0, x1, y0, y1 = int(xs.min()), int(xs.max()) + 1, int(ys.min()), int(ys.max()) + 1
                    boxes.append((c * cw + x0, r * ch + y0, x1 - x0, y1 - y0))
        body = ", ".join("[%d, %d, %d, %d]" % b for b in boxes)
        lines.append(f'  "{name}": {{ w: {w}, h: {h}, cols: {cols}, rows: {rows}, boxes: [{body}] }},')
    lines.append("};")
    dest = os.path.join(ROOT, "src", "components", "kc", "sauce", "sauceSheets.ts")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w", encoding="utf8", newline=chr(10)) as f:
        f.write(chr(10).join(lines) + chr(10))
    print("  wrote", os.path.relpath(dest, ROOT))


def tidy_bottles(im: Image.Image) -> Image.Image:
    """B03: the liquid mask row is pulled in 3 px from the glass (its silhouette is a little wider than the glass base, so liquid showed outside the
    bottle), and the three left/right pixel columns of every cell are cleared (the neighbouring cell's edge peeked in at the cell border)."""
    from PIL import ImageFilter

    cw, ch = im.width // 6, im.height // 3
    out = im.copy()
    for c in range(6):
        box = (c * cw, 2 * ch, (c + 1) * cw, 3 * ch)
        cell = im.crop(box)
        a = cell.getchannel("A").filter(ImageFilter.MinFilter(7))
        cell.putalpha(a)
        out.paste(cell, box[:2])
    px = out.load()
    for r in range(3):
        for c in range(6):
            for y in range(r * ch, (r + 1) * ch):
                # 3 px each side (developer 2026-11-11: a thin line from the neighbouring bottle's clasp showed beside the bottle)
                for x in (c * cw, c * cw + 1, c * cw + 2, (c + 1) * cw - 3, (c + 1) * cw - 2, (c + 1) * cw - 1):
                    r_, g_, b_, _ = px[x, y]
                    px[x, y] = (r_, g_, b_, 0)
    return out


def main() -> int:
    os.makedirs(OUT, exist_ok=True)
    total = 0
    for src, out, scale, quality in JOBS:
        path = os.path.join(SRC, src + ".png")
        if not os.path.exists(path):
            print(f"  skip {src} (not delivered yet)")
            continue
        im = Image.open(path).convert("RGBA")
        if src[:3] not in FULL_SCENES and not has_alpha(im):
            print(f"  REDO {src}: no real transparency (a painted checkerboard). Not built.")
            continue
        if src in CROPS:
            im = im.crop(CROPS[src])
        w, h = im.size
        im = im.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)
        if src == "B03-bottles":
            im = tidy_bottles(im)
        dest = os.path.join(OUT, out + ".webp")
        im.save(dest, "WEBP", quality=quality, method=4)
        size = os.path.getsize(dest)
        total += size
        print(f"  {out:18s} {im.size[0]} x {im.size[1]}  {size / 1024:.0f} KB")
    print(f"total {total / 1024:.0f} KB (budget 1000 KB, lazy loaded for the kit)")
    write_sheet_table()
    return 0


if __name__ == "__main__":
    sys.exit(main())
